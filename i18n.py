def normalize(code: str | None) -> str:
    """'FR', 'fr-FR', 'fr_CH' -> 'fr'; unknown or empty -> FALLBACK."""
    c = (code or "").strip().lower().replace("_", "-").split("-")[0]
    return c if c in LANGUAGES else FALLBACK


def texts(lang: str | None, section: str) -> dict:
    """Texts of one section ('gui' or 'calib') in the given language, English filling any missing key."""
    out = dict(LANGUAGES[FALLBACK][section])
    out.update(LANGUAGES[normalize(lang)].get(section, {}))
    return out


def names() -> dict[str, str]:
    """{code: display name} of the available languages."""
    return {k: v["name"] for k, v in LANGUAGES.items()}
